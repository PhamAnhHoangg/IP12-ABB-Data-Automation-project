"""Build CODE_MAP.md: where each part of the system lives in the code (file + line).

Put a tag comment in the code where a job is done, e.g.

    # @ip12:state_machine  main loop of the robot state machine
    def run_state_machine(): ...

The same tag can appear in several files (code spread over many places).
Run:  python automation/scripts/code_map.py            (from the repo root)
The GitHub Action in .github/workflows/code-map.yml runs it on every push,
so the line numbers in CODE_MAP.md are always current.
"""
import argparse
import os
import re
import subprocess

# order + description of the system steps (same as the n8n system map boxes)
STEPS = [
    ("camera",        "1 · ZED-M camera"),
    ("yolo",          "2 · YOLO detection"),
    ("color_qr",      "3 · Color / QR → priority"),
    ("rules",         "4 · Rules (WP4)"),
    ("state_machine", "5 · State machine"),
    ("robot",         "6 · ABB robot"),
    ("hmi_api",       "7 · HMI screen / API"),
    ("save_data",     "8 · Python saves data"),
]
TAG = re.compile(r"(?:#|//|--|<!--)\s*@ip12:([a-z0-9_]+)\b[ \t]*(.*?)(?:-->)?\s*$", re.I)
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", "data", "build", "dist"}
EXTS = {".py", ".js", ".ts", ".yaml", ".yml", ".json", ".mod", ".prg", ".sys", ".md", ".html", ".sql", ".cpp", ".h"}
ME = os.path.basename(__file__)


def find_tags(root):
    hits = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            if fn == ME or fn == "CODE_MAP.md" or os.path.splitext(fn)[1].lower() not in EXTS:
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            try:
                with open(full, encoding="utf-8", errors="ignore") as f:
                    for no, line in enumerate(f, 1):
                        m = TAG.search(line)
                        if m:
                            hits.setdefault(m.group(1).lower(), []).append((rel, no, m.group(2).strip()))
            except OSError:
                pass
    return hits


def guess_base_url(root):
    try:
        url = subprocess.check_output(["git", "-C", root, "remote", "get-url", "origin"], text=True).strip()
        url = re.sub(r"\.git$", "", url).replace("git@github.com:", "https://github.com/")
        return url + "/blob/main"
    except Exception:
        return None


def build(root, base_url):
    hits = find_tags(root)
    link = (lambda f, n: f"[{f}#L{n}]({base_url}/{f}#L{n})") if base_url else (lambda f, n: f"`{f}:{n}`")
    out = ["# Code Map", "",
           "Auto-generated by `automation/scripts/code_map.py`. Do not edit by hand.",
           "Tag code with `# @ip12:<tag>` and this table updates on every push.", "",
           "| Step | Tag | Where (file#line) | Note |", "|---|---|---|---|"]
    known = [t for t, _ in STEPS]
    for tag, title in STEPS:
        rows = hits.get(tag, [])
        if not rows:
            out.append(f"| {title} | `@ip12:{tag}` | *not tagged yet* | |")
        for i, (f, n, note) in enumerate(rows):
            out.append(f"| {title if i == 0 else ''} | {'`@ip12:' + tag + '`' if i == 0 else ''} | {link(f, n)} | {note} |")
    extra = sorted(t for t in hits if t not in known)
    if extra:
        out += ["", "## Other tags", "", "| Tag | Where | Note |", "|---|---|---|"]
        for t in extra:
            for f, n, note in hits[t]:
                out.append(f"| `@ip12:{t}` | {link(f, n)} | {note} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--base-url", help="e.g. https://github.com/OWNER/REPO/blob/main")
    ap.add_argument("--out", default="CODE_MAP.md")
    a = ap.parse_args()
    md = build(a.root, a.base_url or guess_base_url(a.root))
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(md)
    print(f"wrote {a.out}")
